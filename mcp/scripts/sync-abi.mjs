// Copies only the `abi` arrays of the Elyrion contracts from the Foundry build output
// into src/abi/*.ts so the package does not need forge. Run: pnpm --filter @elyrion/mcp abi
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, "../../contracts/out");
const dest = resolve(here, "../src/abi");
mkdirSync(dest, { recursive: true });

const targets = [
  ["ElyrionIdentity", "identityAbi"],
  ["ElyrionPool", "poolAbi"],
];

for (const [name, exportName] of targets) {
  const json = JSON.parse(readFileSync(resolve(out, `${name}.sol/${name}.json`), "utf8"));
  const body = `// Generated by scripts/sync-abi.mjs from contracts/out/${name}.sol. Do not edit.\nexport const ${exportName} = ${JSON.stringify(json.abi, null, 2)} as const;\n`;
  writeFileSync(resolve(dest, `${name}.ts`), body);
  console.log(`wrote src/abi/${name}.ts (${json.abi.length} entries)`);
}
